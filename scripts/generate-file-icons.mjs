const SIZE = 16;

function svgFor(iconName) {
  const data = getIconData(collection, `file-type-${iconName}`);
  if (!data) return null;
  const { attributes, body } = iconToSVG(data, { height: SIZE });
  const attrStr = Object.entries({
    xmlns: 'http://www.w3.org/2000/svg',
    ...attributes,
    'aria-hidden': 'true',
  })
    .map(([k, v]) => `${k}="${v}"`)
    .join(' ');
  return `<svg ${attrStr}>${body}</svg>`;
}

const svgs = {};
const missing = [];
for (const iconName of new Set(Object.values(EXT_TO_ICON))) {
  const svg = svgFor(iconName);
  if (svg) svgs[iconName] = svg;
  else missing.push(iconName);
}

if (missing.length) {
  console.warn('⚠ No icon found for:', missing.join(', '));
}

const header =
  '// AUTO-GENERATED by scripts/generate-file-icons.mjs — do not edit by hand.\n' +
  '// Source: vscode-icons (via @iconify-json/vscode-icons). Run the script to\n' +
  '// regenerate after changing the extension -> icon map.\n\n';

const extEntries = Object.entries(EXT_TO_ICON)
  .filter(([, name]) => svgs[name])
  .map(([ext, name]) => `  ${JSON.stringify(ext)}: ${JSON.stringify(name)},`)
  .join('\n');

const svgEntries = Object.entries(svgs)
  .map(([name, svg]) => `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`)
  .join('\n');

const out =
  header +
  '/** File extension (lowercase) -> vscode-icons icon name. */\n' +
  'export const EXT_TO_ICON: Record<string, string> = {\n' +
  extEntries +
  '\n};\n\n' +
  '/** Icon name -> inline SVG markup (safe to set via innerHTML). */\n' +
  'export const FILE_ICON_SVGS: Record<string, string> = {\n' +
  svgEntries +
  '\n};\n';

const outPath = join(__dirname, '../src/lib/codeFileIcons.generated.ts');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out, 'utf-8');
console.log(
  `✓ Wrote ${Object.keys(svgs).length} icons / ${
    Object.keys(EXT_TO_ICON).length
  } extensions to ${outPath}`,
);
