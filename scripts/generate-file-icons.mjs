// Iconify data. Run with: `node scripts/generate-file-icons.mjs`
//
// The output embeds real vscode-icons SVG markup (the same icons VS Code's
// "vscode-icons" extension shows) as inline strings keyed by icon name, plus an
// extension -> icon-name map.

